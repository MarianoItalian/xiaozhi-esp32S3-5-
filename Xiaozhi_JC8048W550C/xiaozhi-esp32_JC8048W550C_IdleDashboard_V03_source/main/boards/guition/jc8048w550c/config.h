#ifndef _GUITION_JC8048W550C_CONFIG_H_
#define _GUITION_JC8048W550C_CONFIG_H_

#include <driver/gpio.h>

// Audio: onboard I2S amplifier and external INMP441 microphone.
#define AUDIO_INPUT_SAMPLE_RATE 16000
#define AUDIO_OUTPUT_SAMPLE_RATE 24000

#define AUDIO_I2S_METHOD_SIMPLEX

#define AUDIO_I2S_SPK_GPIO_BCLK GPIO_NUM_0
#define AUDIO_I2S_SPK_GPIO_LRCK GPIO_NUM_18
#define AUDIO_I2S_SPK_GPIO_DOUT GPIO_NUM_17

// These pins are shared with the microSD socket. microSD is disabled in this build.
#define AUDIO_I2S_MIC_GPIO_SCK GPIO_NUM_12
#define AUDIO_I2S_MIC_GPIO_WS GPIO_NUM_13
#define AUDIO_I2S_MIC_GPIO_DIN GPIO_NUM_11

// Display: ST7262-compatible 16-bit RGB panel, 800x480.
#define DISPLAY_WIDTH 800
#define DISPLAY_HEIGHT 480

#define DISPLAY_HSYNC_PIN GPIO_NUM_39
#define DISPLAY_VSYNC_PIN GPIO_NUM_41
#define DISPLAY_DE_PIN GPIO_NUM_40
#define DISPLAY_PCLK_PIN GPIO_NUM_42

// RGB565 data lines in esp_lcd data_gpio_nums order: B0..B4, G0..G5, R0..R4.
#define DISPLAY_DATA_B0_PIN GPIO_NUM_8
#define DISPLAY_DATA_B1_PIN GPIO_NUM_3
#define DISPLAY_DATA_B2_PIN GPIO_NUM_46
#define DISPLAY_DATA_B3_PIN GPIO_NUM_9
#define DISPLAY_DATA_B4_PIN GPIO_NUM_1

#define DISPLAY_DATA_G0_PIN GPIO_NUM_5
#define DISPLAY_DATA_G1_PIN GPIO_NUM_6
#define DISPLAY_DATA_G2_PIN GPIO_NUM_7
#define DISPLAY_DATA_G3_PIN GPIO_NUM_15
#define DISPLAY_DATA_G4_PIN GPIO_NUM_16
#define DISPLAY_DATA_G5_PIN GPIO_NUM_4

#define DISPLAY_DATA_R0_PIN GPIO_NUM_45
#define DISPLAY_DATA_R1_PIN GPIO_NUM_48
#define DISPLAY_DATA_R2_PIN GPIO_NUM_47
#define DISPLAY_DATA_R3_PIN GPIO_NUM_21
#define DISPLAY_DATA_R4_PIN GPIO_NUM_14

#define DISPLAY_BACKLIGHT_PIN GPIO_NUM_2
#define DISPLAY_BACKLIGHT_OUTPUT_INVERT false

#define DISPLAY_MIRROR_X false
#define DISPLAY_MIRROR_Y false
#define DISPLAY_SWAP_XY false
#define DISPLAY_OFFSET_X 0
#define DISPLAY_OFFSET_Y 0

// GT911 capacitive touch controller. Interrupt is intentionally unused because GPIO18 is audio
// LRCK.
#define TOUCH_I2C_PORT I2C_NUM_0
#define TOUCH_I2C_SDA_PIN GPIO_NUM_19
#define TOUCH_I2C_SCL_PIN GPIO_NUM_20
#define TOUCH_RESET_PIN GPIO_NUM_38
#define TOUCH_INTERRUPT_PIN GPIO_NUM_NC
#define TOUCH_SWAP_XY false
#define TOUCH_MIRROR_X false
#define TOUCH_MIRROR_Y false

#endif  // _GUITION_JC8048W550C_CONFIG_H_
